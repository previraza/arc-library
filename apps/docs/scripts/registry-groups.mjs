/**
 * Builds lib/registry-groups.ts from the grouping already written in the repository README, so the docs site and the
 * README never drift: the README owns the curated order, this script mirrors it into typed data.
 *
 * Usage: pnpm --filter @manicat/docs groups
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

// The app writes lib/registry-groups.ts; the README it reads and the registry it checks live in the Arc package.
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..", "..");
const readme = readFileSync(join(repo, "README.md"), "utf8");
const registry = JSON.parse(readFileSync(join(repo, "packages", "manicat", "registry.json"), "utf8"));

const known = new Set(registry.items.map((item) => item.name));

const section = (heading) => {
  const start = readme.indexOf(`\n## ${heading}\n`);
  if (start < 0) throw new Error(`README section not found: ${heading}`);
  const rest = readme.slice(start + 1);
  const end = rest.slice(1).search(/\n## /);
  return end < 0 ? rest : rest.slice(0, end + 1);
};

const names = (block) =>
  [...block.matchAll(/^\|\s*\[([^\]]+)\]\(https:\/\/(?:uiarc|manicat)\.dev\/components\/(?:blocks\/)?([a-z0-9-]+)\)/gm)].map(
    (match) => match[2],
  );

const all = [];

const components = [];
let category = null;
let group = null;
for (const line of section("Components").split("\n")) {
  const categoryMatch = /^### (.+)$/.exec(line);
  if (categoryMatch) {
    category = { title: categoryMatch[1], groups: [] };
    components.push(category);
    group = null;
    continue;
  }
  const groupMatch = /^\*\*(.+)\*\*$/.exec(line.trim());
  if (groupMatch && category) {
    group = { title: groupMatch[1], items: [] };
    category.groups.push(group);
    continue;
  }
  if (line.startsWith("| [") && group) {
    group.items.push(...names(line));
    all.push(...names(line));
  }
}

const blocks = [];
for (const line of section("Blocks").split("\n")) {
  const groupMatch = /^### (.+)$/.exec(line);
  if (groupMatch) {
    group = { title: groupMatch[1], items: [] };
    blocks.push(group);
    continue;
  }
  if (line.startsWith("| [") && group) {
    group.items.push(...names(line));
    all.push(...names(line));
  }
}

const grouped = [...new Set(all)];
const missing = grouped.filter((name) => !known.has(name));
const ungrouped = [...known].filter((name) => name !== "manicat-foundation" && !grouped.includes(name));
if (missing.length) throw new Error(`README lists unknown registry items: ${missing.join(", ")}`);
if (ungrouped.length) console.warn(`Warning, registry items with no group: ${ungrouped.join(", ")}`);

const formatCategory = (category) => {
  const groups = category.groups
    .map((group) => `      { title: ${JSON.stringify(group.title)}, items: [${group.items.map((name) => JSON.stringify(name)).join(", ")}] },`)
    .join("\n");
  return `  {\n    title: ${JSON.stringify(category.title)},\n    groups: [\n${groups}\n    ],\n  },`;
};

const formatGroup = (group) =>
  `  { title: ${JSON.stringify(group.title)}, items: [${group.items.map((name) => JSON.stringify(name)).join(", ")}] },`;

const output = `/**
 * Generated by scripts/registry-groups.mjs. Edit the README tables instead.
 */
import type { ComponentGroups, BlockGroups } from "./registry-groups-types";

export const componentGroups: ComponentGroups = [
${components.map(formatCategory).join("\n")}
];

export const blockGroups: BlockGroups = [
${blocks.map(formatGroup).join("\n")}
];
`;

mkdirSync(join(root, "lib"), { recursive: true });
writeFileSync(join(root, "lib/registry-groups.ts"), output);
console.log(`Wrote lib/registry-groups.ts: ${grouped.length} items in ${components.length} categories and ${blocks.length} block groups.`);