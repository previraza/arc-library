/**
 * Prepares the Swift viewer: copies the Usage snippets of the docs into Sources/ManicatPreview/Demos and writes the list the
 * viewer shows. A snippet is a SwiftUI view, so the first `struct X: View` of each file is the demo. Swift cannot discover
 * types at build time, which is why this step exists (`pnpm --filter @manicat/preview-swift generate`).
 */
import { execFileSync } from "node:child_process";
import { readFile, readdir, writeFile } from "node:fs/promises";

const dir = new URL("../Sources/ManicatPreview/", import.meta.url);
execFileSync("node", [new URL("../../../packages/manicat/scripts/sync-usage-demos.mjs", import.meta.url).pathname, "swift", new URL("Demos", dir).pathname], { stdio: "inherit" });

const demos = [];
for (const file of (await readdir(new URL("Demos/", dir))).filter(name => name.endsWith(".swift")).sort()) {
  const source = await readFile(new URL(`Demos/${file}`, dir), "utf8");
  const view = /struct\s+(\w+)\s*:\s*View/.exec(source)?.[1];
  if (view) demos.push({ item: file.slice(0, -".swift".length), view });
  else console.warn(`${file}: no "struct X: View" found, skipped.`);
}

const body = `// Generated by scripts/generate-demos.mjs. Do not edit.
import SwiftUI

struct AnyDemo {
    let item: String
    let make: () -> AnyView
}

let generatedDemos: [AnyDemo] = [
${demos.map(({ item, view }) => `    AnyDemo(item: "${item}", make: { AnyView(${view}()) }),`).join("\n")}
]
`;
await writeFile(new URL("DemoRegistry.generated.swift", dir), body);
console.log(`Registered ${demos.length} Swift demos.`);
