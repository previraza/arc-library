/**
 * Writes Sources/ManicatPreview/DemoRegistry.generated.swift from the demos found in Sources/ManicatPreview/Demos: every
 * `struct XDemo: ManicatDemo`. Swift has no way to discover types at build time, so this is the one step between adding a
 * demo file and seeing it in the viewer (`pnpm --filter @manicat/preview-swift generate`).
 */
import { readFile, readdir, writeFile } from "node:fs/promises";

const dir = new URL("../Sources/ManicatPreview/", import.meta.url);
const names = [];
for (const file of (await readdir(new URL("Demos/", dir))).filter(name => name.endsWith(".swift")).sort()) {
  const source = await readFile(new URL(`Demos/${file}`, dir), "utf8");
  for (const match of source.matchAll(/struct\s+(\w+)\s*:\s*ManicatDemo/g)) names.push(match[1]);
}

const body = `// Generated by scripts/generate-demos.mjs. Do not edit.
import SwiftUI

struct AnyDemo {
    let item: String
    let make: () -> AnyView
}

let generatedDemos: [AnyDemo] = [
${names.map(name => `    AnyDemo(item: ${name}.item, make: { AnyView(${name}()) }),`).join("\n")}
]
`;
await writeFile(new URL("DemoRegistry.generated.swift", dir), body);
console.log(`Registered ${names.length} Swift demos.`);
